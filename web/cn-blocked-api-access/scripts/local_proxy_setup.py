#!/usr/bin/env python3
"""Generate a local mihomo config from nodes already configured in a router's OpenClash.

Purpose: reach hosts unreachable from the LAN because the router's final rule is
`MATCH -> DIRECT` (the domain never enters a proxy group) while the domain is also
DNS-poisoned / SNI-filtered — i.e. "another node won't help". This builds a second, local
egress whose only rule is `MATCH -> PROXY`, without touching the router configuration.

Read-only on the router (one `cat` over SSH). Credentials are never printed; the emitted
config is chmod 600.

Usage: python3 local_proxy_setup.py [region-regex]   default: Hong
       Use the ENGLISH city name — node names usually carry escaped flag codepoints,
       so a Chinese name like the Hong Kong characters matches nothing.
"""
import os
import re
import subprocess
import sys

ROUTER = "root@192.0.2.10"
SSH_PORT = "2222"
OPENCLASH_YAML = "/etc/openclash/9.1.yaml"   # running config: confirm via `ps w | grep -i clash`
SSH = ["ssh", "-p", SSH_PORT, "-o", "BatchMode=yes", "-o", "StrictHostKeyChecking=no", ROUTER]
OUT_DIR = "~/.hermes/mihomo"
CONF = os.path.join(OUT_DIR, "config.yaml")
PORT = 7899
REGION = sys.argv[1] if len(sys.argv) > 1 else "Hong"


def sh(cmd):
    return subprocess.run(cmd, capture_output=True, text=True, timeout=90).stdout


def unescape(name):
    return name.encode("utf-8").decode("unicode_escape") if "\\u" in name.lower() else name


def main():
    raw = sh(SSH + [f"cat {OPENCLASH_YAML}"])
    if not raw.strip():
        print("router config read failed")
        return 1
    m = re.search(r"^proxies:\n(.*?)^proxy-groups:", raw, re.S | re.M)
    if not m:
        print("no proxies: block found")
        return 1
    nodes = []
    for entry in re.split(r"\n(?=- name:)", m.group(1)):
        if not entry.strip().startswith("- name:"):
            continue
        d = {}
        for line in entry.splitlines():
            line = line.strip().lstrip("- ")
            if ":" in line:
                k, v = line.split(":", 1)
                d[k.strip()] = v.strip().strip("'\"")
        if d.get("name") and re.search(REGION, d["name"]):
            nodes.append(d)
    if not nodes:
        print(f"no nodes matched {REGION!r} — use the English city name")
        return 1

    lines = [
        "# generated by cn-blocked-api-access/scripts/local_proxy_setup.py — re-run to refresh",
        f"# region filter: {REGION}   nodes: {len(nodes)}",
        f"mixed-port: {PORT}",
        "allow-lan: false",
        "bind-address: 127.0.0.1",
        "mode: rule",
        "log-level: warning",
        "ipv6: false",
        "unified-delay: true",
        "tcp-concurrent: true",
        "dns:",
        "  enable: true",
        "  ipv6: false",
        "  enhanced-mode: fake-ip",
        "  fake-ip-range: 198.18.0.1/16",
        "  nameserver: [203.0.113.1, 203.0.113.1]",
        "  proxy-server-nameserver: [203.0.113.1, 203.0.113.1]",
        "proxies:",
    ]
    names = []
    for n in nodes:
        name = unescape(n["name"])
        names.append(name)
        lines.append(
            f"  - {{name: '{name}', type: {n.get('type', 'anytls')}, server: {n.get('server','')}, "
            f"port: {n.get('port','443')}, password: '{n.get('password','')}', "
            f"sni: {n.get('sni','')}, client-fingerprint: {n.get('client-fingerprint','chrome')}, "
            f"skip-cert-verify: {n.get('skip-cert-verify','true')}, udp: true}}"
        )
    lines += ["proxy-groups:", "  - name: PROXY", "    type: select", "    proxies:"]
    lines += [f"      - '{x}'" for x in names]
    lines += ["rules:", "  - MATCH,PROXY", ""]

    os.makedirs(OUT_DIR, exist_ok=True)
    with open(CONF, "w") as f:
        f.write("\n".join(lines))
    os.chmod(CONF, 0o600)
    print(f"wrote {CONF} ({len(nodes)} nodes, port {PORT})")
    print("nodes:", ", ".join(names))
    return 0


if __name__ == "__main__":
    sys.exit(main())
